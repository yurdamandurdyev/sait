import {readFile,writeFile} from 'node:fs/promises';
const read=name=>readFile(new URL(name,import.meta.url),'utf8');
const model=(await read('./model.js')).replace(/^export /gm,'');
const app=(await read('./app.js')).replace(/^import .* from '\.\/model\.js';\n/,'');
const bundle='// Generated by npm run build.\n(()=>{\n'+model+'\n'+app+'\n})();\n';
await writeFile(new URL('./bundle.js',import.meta.url),bundle);
const images=await Promise.all(Array.from({length:5},async(_,i)=>'data:image/svg+xml;base64,'+Buffer.from(await read(`./assets/meal-${i}.svg`)).toString('base64')));
const standalone=bundle.replace('const image=r=>`./assets/meal-${r.id}.svg`','const image=r=>'+JSON.stringify(images)+'[r.id]');
const html=(await read('./index.template.html')).replace('<link rel="stylesheet" href="./style.css">','<style>'+await read('./style.css')+'</style>').replace('<script src="./bundle.js"></script>','<script>'+standalone.replace(/<\/script/gi,'<\\/script')+'</script>');
await writeFile(new URL('./index.html',import.meta.url),html);
