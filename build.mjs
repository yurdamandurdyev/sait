import {readFile,writeFile} from 'node:fs/promises';
const read=name=>readFile(new URL(name,import.meta.url),'utf8');
const modules=await Promise.all(['model.js','art.js','scene.js','app.js'].map(async name=>(await read(name)).replace(/^import .* from .*;\n/gm,'').replace(/^export /gm,'')));
const bundle='// Generated by npm run build.\n(()=>{\n'+modules.join('\n')+'\n})();\n';
await writeFile(new URL('./bundle.js',import.meta.url),bundle);
const css=await read('./style.css');
const html=(await read('./index.template.html')).replace('<link rel="stylesheet" href="./style.css">',()=>'<style>'+css+'</style>').replace('<script src="./bundle.js"></script>',()=>'<script>'+bundle.replace(/<\/script/gi,'<\\/script')+'</script>');
await writeFile(new URL('./index.html',import.meta.url),html);
console.log('Built standalone index.html: '+Math.round(Buffer.byteLength(html)/1024)+' KB, no external dependencies.');
